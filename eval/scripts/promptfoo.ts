// pnpm eval:promptfoo — exports the sample set as a promptfoo config (eval/promptfoo/) so other
// developers can run control group A with `npx promptfoo eval -c eval/promptfoo/promptfooconfig.yaml`.
// promptfoo is not a dependency of this repo. YAML is written as JSON-compatible YAML 1.2.
import fs from 'node:fs'
import path from 'node:path'
import { EVAL_DIR, SAMPLES_DIR } from '../lib/config'
import { A_SYSTEM, A_USER_GOLD } from '../lib/group-a'
import { describeFacts } from '../lib/group-a'
import { normalizePhone } from '../lib/page-facts'
import { loadSamples, type Sample } from '../lib/samples'

const OUT = path.join(EVAL_DIR, 'promptfoo')
const q = (s: string): string => JSON.stringify(s)

// promptfoo itself asks for raw HTML; the JSON wrapper line exists only for this repo's provider interface.
const SYSTEM = A_SYSTEM.split('\n')
  .filter((line) => !line.includes('JSON'))
  .join('\n')

/** Same price pattern as eval/lib/page-facts.ts, applied to the raw output in promptfoo. */
const PRICE_JS = String.raw`/¥\s*(\d+(?:\.\d+)?)(?:\s*元(?![旦宵气素]))?|(?<![\d.])(\d+(?:\.\d+)?)\s*元(?![旦宵气素])/gu`

function testsFor(sample: Sample): string[] {
  const prices = sample.gold.items.flatMap((i) => (i.price ? [i.price.amount] : []))
  const lines = [
    `  - description: ${q(sample.id)}`,
    `    vars:`,
    `      facts: ${q(describeFacts(sample.gold))}`,
    `    assert:`,
  ]
  for (const item of sample.gold.items) {
    lines.push(
      `      - type: icontains`,
      `        value: ${q(item.name)}`,
      `        metric: product_name`,
    )
  }
  const pricesJs =
    `const gold = ${JSON.stringify(prices)}; ` +
    `const found = [...output.normalize('NFKC').matchAll(${PRICE_JS})].map((m) => Number(m[1] ?? m[2])); ` +
    `return gold.every((g) => found.some((v) => Math.abs(v - g) < 0.005)) && found.every((v) => gold.some((g) => Math.abs(v - g) < 0.005));`
  lines.push(
    `      - type: javascript`,
    `        value: ${q(pricesJs)}`,
    `        metric: prices_exact`,
  )
  if (sample.gold.shop.phone) {
    const digits = normalizePhone(sample.gold.shop.phone)
    lines.push(
      `      - type: javascript`,
      `        value: ${q(`return output.replace(/\\D/g, '').includes(${q(digits)});`)}`,
      `        metric: phone_present`,
    )
  }
  return lines.map((line) => line.slice(2)) // the test list is the document root
}

function main(): void {
  const samples = loadSamples(SAMPLES_DIR)
  fs.mkdirSync(OUT, { recursive: true })
  const prompt = [
    { role: 'system', content: SYSTEM },
    { role: 'user', content: A_USER_GOLD.replace('{facts}', '{{facts}}') },
  ]
  fs.writeFileSync(path.join(OUT, 'prompt-a.json'), JSON.stringify(prompt, null, 2) + '\n')
  const tests = [
    '# Generated by pnpm eval:promptfoo from eval/samples/*/gold.json. Do not edit by hand.',
    ...samples.flatMap(testsFor),
  ]
  fs.writeFileSync(path.join(OUT, 'tests.yaml'), tests.join('\n') + '\n')
  const config = [
    '# 实招 Shizhao control group A ("AI writes the whole page") as a promptfoo eval.',
    '# Generated by pnpm eval:promptfoo. Run: npx promptfoo@latest eval -c eval/promptfoo/promptfooconfig.yaml',
    '# Assertions check the raw HTML (script text included), so they approximate eval/lib/page-metrics.ts.',
    '# The provider below is an example (any OpenAI-compatible endpoint); set the API key env var it names.',
    'description: "实招 Shizhao 对照组 A：AI 直接写整页（商品名、价格、电话是否与商家事实表一致）"',
    'prompts:',
    '  - file://prompt-a.json',
    'providers:',
    '  - id: openai:chat:qwen-plus',
    '    config:',
    '      apiBaseUrl: https://dashscope.aliyuncs.com/compatible-mode/v1',
    '      apiKeyEnvar: DASHSCOPE_API_KEY',
    '      temperature: 0.6',
    'tests: file://tests.yaml',
    '',
  ]
  fs.writeFileSync(path.join(OUT, 'promptfooconfig.yaml'), config.join('\n'))
  console.log(
    `[eval] promptfoo config for ${samples.length} samples written to ${path.relative(process.cwd(), OUT)}/`,
  )
}

main()
